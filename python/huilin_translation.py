"""Add Hanyu pinyin and English equivalents to the Hui Lin index.

Reads data/dictionary/huilin_index.tsv, produced by huilin_index.py, and writes
data/dictionary/huilin.tsv with the same rows and the Hanyu pinyin (field 4)
and English equivalent (field 5) filled in. All other fields are copied
unchanged.

The pinyin and English for each headword are generated by Claude through the
Anthropic API, using the body of Hui Lin's entry in T 2128 (in the Notes field)
as context. If the Anthropic API call fails, the entry is tried with Gemini on
Vertex AI instead. If both fail, the fields are left as \\N.

Each row is written and flushed to disk as soon as it is processed. If the
program stops, run it again: rows already translated in the output file are
kept, and rows that are missing or have no English equivalent are processed.

If the Anthropic API reports that the credit balance has run out or that the
API key is not valid, the program stops without falling back to Gemini for the
remaining entries. Fix the problem and run it again to continue with Claude
from the first unfinished entry. The same applies if you stop the program with
Ctrl-C.

Setup:

  # Create a Python virtual environment in the top level directory of the
  # project (one time only) and install the dependencies into it:
  python3 -m venv .venv
  source .venv/bin/activate
  pip install --upgrade pip
  pip install anthropic google-genai

  # In each new terminal session, activate the virtual environment again
  # before running the program (run `deactivate` to leave it):
  source .venv/bin/activate

  # If you use conda, run `conda deactivate` first so that `python3` and `pip`
  # refer to the virtual environment and not the conda base environment.

  # Anthropic API: an API key from https://platform.claude.com (API usage is
  # billed separately from Claude Pro/Max subscriptions)
  export ANTHROPIC_API_KEY=...

  # Gemini via Vertex AI: Google Cloud Application Default Credentials
  gcloud auth application-default login
  export GOOGLE_CLOUD_PROJECT=<your project ID>

Usage (from the top level directory of the project):

  python3 python/huilin_translation.py [--limit N] [--workers N]
"""

import argparse
import concurrent.futures
import json
import os
import sys
import threading

import anthropic
from google import genai
from google.genai import types

BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DICT_DIR = os.path.join(BASE_DIR, 'data', 'dictionary')
INPUT_FILE = os.path.join(DICT_DIR, 'huilin_index.tsv')
OUTPUT_FILE = os.path.join(DICT_DIR, 'huilin.tsv')
CNOTES_DICT = os.path.join(DICT_DIR, 'cnotes_zh_en_dict.tsv')

NULL = '\\N'
PINYIN_FIELD = 3
ENGLISH_FIELD = 4

CLAUDE_MODEL = 'claude-sonnet-5-5'
GEMINI_MODEL = 'gemini-3.8-flash'
GEMINI_LOCATION = 'global'

SYSTEM_PROMPT = """\
You are a lexicographer of Buddhist Chinese compiling entries for a \
Chinese-English dictionary of the Chinese Buddhist canon.

You will be given a headword from Hui Lin's 一切經音義 'The Sounds and \
Meanings of all the Terms in the Canonical Texts' (T 2128, Tang dynasty) \
together with the body of Hui Lin's entry. The entry body usually gives \
fanqie (反切) spellings for the pronunciation, glosses from earlier \
dictionaries such as the 說文, 廣雅, and 考聲, and notes on the graphs. It \
may also identify a Sanskrit term that the headword transliterates or \
translates.

Return:
- pinyin: the modern Mandarin Hanyu pinyin of the headword, with tone marks, \
lower case, with one syllable for each Chinese character and a single space \
between syllables, for example "èr yí" for 二儀 and "qián hán shǔ" for 潛寒暑. \
Where an existing dictionary entry is given, follow its reading. Use the fanqie in the entry to choose between alternative readings \
of a polyphonic character.
- english: a concise English equivalent of the headword as it is used in \
the context described by the entry, suitable for the English equivalent field \
of a dictionary entry: a word or short phrase, lower case unless it is a \
proper noun, without explanation. For a transliteration of Sanskrit, give the \
Sanskrit term in IAST, followed by a short English gloss after a comma if the \
Sanskrit term alone is not clear, for example "saṃghāṭī, outer robe".
"""

OUTPUT_SCHEMA = {
    'type': 'object',
    'properties': {
        'pinyin': {'type': 'string'},
        'english': {'type': 'string'},
    },
    'required': ['pinyin', 'english'],
    'additionalProperties': False,
}


def load_reference_dict(path):
  """Maps traditional headwords to (pinyin, english) from the cnotes dictionary.
  """
  ref = {}
  with open(path, 'r', encoding='utf-8') as f:
    for line in f:
      if line.startswith('#'):
        continue
      fields = line.rstrip('\n').split('\t')
      if len(fields) < 5:
        continue
      trad = fields[2] if fields[2] != NULL else fields[1]
      ref.setdefault(trad, (fields[3], fields[4]))
  return ref


def build_prompt(fields, ref):
  """Builds the user prompt for one dictionary row."""
  simp, trad, notes = fields[1], fields[2], fields[14]
  headword = trad if trad != NULL else simp
  lines = ['Headword: ' + headword, "Hui Lin's entry: " + notes]
  if headword in ref:
    pinyin, english = ref[headword]
    lines.append('Existing general dictionary entry (may be a different '
                 'sense): pinyin {}, English {}'.format(pinyin, english))
  return '\n'.join(lines)


class StopRun(Exception):
  """An Anthropic API error that every later entry would also get, such as
  no credit left or an invalid API key."""


def is_credit_exhausted(e):
  """Returns True if an Anthropic API error means the credit has run out."""
  if e.status_code == 402 or getattr(e, 'type', None) == 'billing_error':
    return True
  # The API has also reported a low credit balance as a 400
  # invalid_request_error, which has no more specific type
  return e.status_code == 400 and 'credit balance' in str(e).lower()


def clean(value):
  """Makes a model output value safe for a TSV field."""
  value = ' '.join(str(value).split())
  return value if value else NULL


class Translator:
  """Translates headwords with Claude, falling back to Gemini."""

  def __init__(self, claude_model, gemini_model, project):
    self.claude_model = claude_model
    self.gemini_model = gemini_model
    self.claude = anthropic.Anthropic()
    self.gemini = genai.Client(vertexai=True, project=project,
                               location=GEMINI_LOCATION)
    # Set when the run is stopping, so queued entries make no more API calls
    self.stop = threading.Event()

  def translate_claude(self, prompt):
    """Returns (pinyin, english) from Claude or raises an exception."""
    response = self.claude.beta.messages.create(
        model=self.claude_model,
        max_tokens=16000,
        system=SYSTEM_PROMPT,
        messages=[{'role': 'user', 'content': prompt}],
        output_config={
            'effort': 'medium',
            'format': {'type': 'json_schema', 'schema': OUTPUT_SCHEMA},
        },
        # Retry on another model server-side if a safety classifier declines
        betas=['server-side-fallback-2026-07-01'],
        fallbacks='default',
    )
    if response.stop_reason == 'refusal':
      raise RuntimeError('Claude declined the request')
    if response.stop_reason == 'max_tokens':
      raise RuntimeError('Claude response truncated at max_tokens')
    text = next(b.text for b in response.content if b.type == 'text')
    data = json.loads(text)
    return data['pinyin'], data['english']

  def translate_gemini(self, prompt):
    """Returns (pinyin, english) from Gemini or raises an exception."""
    response = self.gemini.models.generate_content(
        model=self.gemini_model,
        contents=prompt,
        config=types.GenerateContentConfig(
            system_instruction=SYSTEM_PROMPT,
            response_mime_type='application/json',
            response_schema={
                'type': 'OBJECT',
                'properties': {
                    'pinyin': {'type': 'STRING'},
                    'english': {'type': 'STRING'},
                },
                'required': ['pinyin', 'english'],
            },
        ),
    )
    data = json.loads(response.text)
    return data['pinyin'], data['english']

  def translate(self, luid, prompt):
    """Returns (pinyin, english, source), with \\N values if both APIs fail.

    Raises StopRun if the Anthropic credit has run out or authentication
    failed, or if another entry has already stopped the run.
    """
    if self.stop.is_set():
      raise StopRun('run is stopping')
    try:
      pinyin, english = self.translate_claude(prompt)
      return clean(pinyin), clean(english), 'claude'
    except anthropic.APIStatusError as e:
      if is_credit_exhausted(e):
        self.stop.set()
        raise StopRun('the Anthropic credit balance has run out ({}). '
                      'Add credit'.format(e)) from e
      if isinstance(e, anthropic.AuthenticationError):
        self.stop.set()
        raise StopRun('Anthropic authentication failed ({}). {}'.format(
            e, credential_hint())) from e
      self.log_claude_error(luid, e)
    except anthropic.APIConnectionError as e:
      log('{}: Anthropic connection error: {}'.format(luid, e))
    except Exception as e:  # pylint: disable=broad-except
      # e.g. no credentials configured, or unexpected response content
      log('{}: Anthropic call failed: {!r}'.format(luid, e))
    try:
      pinyin, english = self.translate_gemini(prompt)
      return clean(pinyin), clean(english), 'gemini'
    except Exception as e:  # pylint: disable=broad-except
      log('{}: Gemini call failed: {!r}'.format(luid, e))
    return NULL, NULL, 'none'

  @staticmethod
  def log_claude_error(luid, e):
    """Logs an Anthropic API status error."""
    if isinstance(e, anthropic.RateLimitError):
      log('{}: Anthropic rate limited: {}'.format(luid, e))
    else:
      log('{}: Anthropic API error {}: {}'.format(luid, e.status_code, e))


def credential_hint():
  """Says which Anthropic credential environment variables are set."""
  names = [n for n in ('ANTHROPIC_API_KEY', 'ANTHROPIC_AUTH_TOKEN',
                       'ANTHROPIC_PROFILE') if os.environ.get(n)]
  hint = 'Set: {}'.format(', '.join(names) if names else 'none')
  if not os.environ.get('ANTHROPIC_API_KEY'):
    hint += ('. ANTHROPIC_API_KEY is not set, so a bearer token or saved '
             'profile was used instead; export ANTHROPIC_API_KEY')
  elif len(names) > 1:
    hint += '. Check that ANTHROPIC_API_KEY holds the key'
  else:
    hint += '. Check that ANTHROPIC_API_KEY holds the whole key'
  return hint


_log_lock = threading.Lock()


def log(message):
  with _log_lock:
    print(message, file=sys.stderr, flush=True)


def read_rows(path, translated_only=False):
  """Returns {lexical unit number: fields} for the rows in a TSV file.

  If translated_only is set, rows with no English equivalent are left out.
  """
  rows = {}
  if not os.path.exists(path):
    return rows
  with open(path, 'r', encoding='utf-8') as f:
    for line in f:
      if line.startswith('#') or not line.strip():
        continue
      fields = line.rstrip('\n').split('\t')
      if translated_only and fields[ENGLISH_FIELD] == NULL:
        continue
      rows[fields[0]] = fields
  return rows


def rewrite(path, header, rows):
  """Atomically replaces the file with the header and rows sorted by number."""
  tmp = path + '.tmp'
  with open(tmp, 'w', encoding='utf-8') as out:
    if header:
      out.write(header)
    for fields in sorted(rows, key=lambda r: int(r[0])):
      out.write('\t'.join(fields) + '\n')
    out.flush()
    os.fsync(out.fileno())
  os.replace(tmp, path)


def main():
  parser = argparse.ArgumentParser(description=__doc__.split('\n')[0])
  parser.add_argument('--input', default=INPUT_FILE)
  parser.add_argument('--output', default=OUTPUT_FILE)
  parser.add_argument('--limit', type=int, default=0,
                      help='Maximum number of new entries to process')
  parser.add_argument('--workers', type=int, default=4,
                      help='Number of concurrent API requests')
  parser.add_argument('--claude-model', default=CLAUDE_MODEL)
  parser.add_argument('--gemini-model', default=GEMINI_MODEL)
  parser.add_argument('--max-failures', type=int, default=20,
                      help='Stop after this many consecutive entries where '
                           'both APIs failed')
  args = parser.parse_args()

  key = os.environ.get('ANTHROPIC_API_KEY')
  if key and not key.startswith('sk-ant-'):
    # e.g. curly quotes or spaces copied in with the key
    log("Error: ANTHROPIC_API_KEY does not start with 'sk-ant-' (it starts "
        'with {!r}). Set it again with plain quotes or none: '
        'export ANTHROPIC_API_KEY=sk-ant-...'.format(key[:1]))
    sys.exit(1)

  project = os.environ.get('GOOGLE_CLOUD_PROJECT')
  if not project:
    log('Warning: GOOGLE_CLOUD_PROJECT is not set; the Gemini fallback '
        'will fail')

  ref = load_reference_dict(CNOTES_DICT)
  with open(args.input, 'r', encoding='utf-8') as f:
    header = next((line for line in f if line.startswith('#')), None)
  rows = [r for r in read_rows(args.input).values() if len(r) == 16]

  # Keep the rows already translated; rows that failed before are retried
  done = read_rows(args.output, translated_only=True)
  rewrite(args.output, header, done.values())
  todo = [r for r in rows if r[0] not in done]
  if args.limit:
    todo = todo[:args.limit]
  log('{} entries done, {} to process'.format(len(done), len(todo)))

  translator = Translator(args.claude_model, args.gemini_model, project)
  counts = {'claude': 0, 'gemini': 0, 'none': 0}
  consecutive_failures = 0
  with open(args.output, 'a', encoding='utf-8') as out:
    with concurrent.futures.ThreadPoolExecutor(args.workers) as pool:
      futures = [pool.submit(translator.translate, fields[0],
                             build_prompt(fields, ref))
                 for fields in todo]
      # Write each row as soon as it and the rows before it are done
      for i, (fields, future) in enumerate(zip(todo, futures), 1):
        try:
          pinyin, english, source = future.result()
        except (StopRun, KeyboardInterrupt) as e:
          # Leave this row and the rest unwritten so the next run does them
          translator.stop.set()
          pool.shutdown(wait=True, cancel_futures=True)
          if isinstance(e, StopRun):
            log('Stopping: {}, and run again to continue from entry '
                '{}.'.format(e, fields[0]))
          else:
            log('Interrupted; run again to continue from entry {}'.format(
                fields[0]))
          break
        fields[PINYIN_FIELD] = pinyin
        fields[ENGLISH_FIELD] = english
        out.write('\t'.join(fields) + '\n')
        out.flush()
        os.fsync(out.fileno())
        counts[source] += 1
        if i % 100 == 0 or i == len(todo):
          log('{}/{} written: {}'.format(i, len(todo), counts))
        consecutive_failures = consecutive_failures + 1 if source == 'none' else 0
        if args.max_failures and consecutive_failures >= args.max_failures:
          log('Stopping after {} consecutive failures'.format(
              consecutive_failures))
          pool.shutdown(wait=True, cancel_futures=True)
          break

  # Put rows retried in this run back in order
  rewrite(args.output, header, read_rows(args.output).values())
  log('Done: {}'.format(counts))


if __name__ == '__main__':
  main()
